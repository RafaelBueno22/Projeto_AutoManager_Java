        private void carregarClientes(){
            String sql = """
                         SELECT id, nome
                         FROM cliente
                         ORDER BY nome
                         """;
            
            cbCliente.removeAllItems();
            idClientes.clear();
            
            try(Connection conex = Conexao.conectar();
                PreparedStatement stmt = conex.prepareStatement(sql);
                ResultSet rs = stmt.executeQuery()){
                
                while(rs.next()){
                    int id = rs.getInt("id");
                    String nome = rs.getString("nome");
                    
                    cbCliente.addItem(nome);
                    idClientes.add(id);
                    
                    
                }
                
                cbCliente.setSelectedIndex(-1);
            }catch(SQLException erro){
                JOptionPane.showMessageDialog(this, "Erro ao carregar clientes: " +erro.getMessage());
            }
            
        }

       private void atualizarTabela(){
           String sql = """
                        SELECT v.id, c.nome AS cliente, v.placa,
                               v.marca, v.modelo, v.ano, v.cor,
                               v.observacao, v.ativo
                        FROM veiculo v
                        JOIN cliente c ON v.cliente_id = c.id
                        ORDER BY v.id
                        """;
           
           DefaultTableModel modelo = (DefaultTableModel) tblVeiculos.getModel();
           modelo.setRowCount(0);
           
           try(Connection conex = Conexao.conectar();
               PreparedStatement stmt = conex.prepareStatement(sql);
               ResultSet rs = stmt.executeQuery()){
               
               while(rs.next()){
                   modelo.addRow(new Object []{
                       rs.getInt("id"),
                       rs.getString("cliente"),
                       rs.getString("placa"),
                       rs.getString("marca"),
                       rs.getString("modelo"),
                       rs.getInt("ano"),
                       rs.getString("cor"),
                       rs.getString("observacao"),
                       rs.getBoolean("ativo")
                   });
               }
           }catch(SQLException erro){
               JOptionPane.showMessageDialog(this, "Erro ao carregar veículo: " +erro.getMessage());
           }
       }

