    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linha = tblVeiculos.getSelectedRow();
        if(linha == -1){
           JOptionPane.showMessageDialog(this, "Selecione um Veículo.");
        return; 
        
        }
        
        int id = Integer.parseInt(txtID.getText().trim());
        
        int confirmar = JOptionPane.showConfirmDialog(this,
                                                      "Deseja realmente excluir este veículo?",
                                                      "Confirmar exclusão",
                                                      JOptionPane.YES_NO_OPTION);
        
        if(confirmar != JOptionPane.YES_OPTION) return;   
        
        String sqlVerificar = """
                              SELECT COUNT (*)
                              FROM ordem_servico
                              WHERE veiculo_id = ?
                              """;
        
        try(Connection conex = Conexao.conectar()){
            int quantidade = 0;
            
            try(PreparedStatement stmt = conex.prepareStatement(sqlVerificar)){
                stmt.setInt(1, id);
                
                try(ResultSet rs = stmt.executeQuery()){
                    if(rs.next()){
                        quantidade = rs.getInt(1);
                    }
                }
            }    
            
            if(quantidade > 0){
               int opcao = JOptionPane.showConfirmDialog(this,
                                                         "Este veículo possui " + quantidade
                                                       + " Ordem(ns) de Serviço vinculada(s).\n"
                                                       + "Não é possível excluí-lo sem perder o histórico.\n\n"
                                                       + "Deseja desativar o veículo?",
                                                         "Veículo com histórico",
                                                          JOptionPane.YES_NO_OPTION);
               
               if(opcao != JOptionPane.YES_OPTION)return;
               
               String sqlDesativar = """
                                     UPDATE veiculo
                                     SET ativo = FALSE
                                     WHERE id = ?
                                     """;
               
               try(PreparedStatement stmt = conex.prepareStatement(sqlDesativar)){
                   stmt.setInt(1, id);
                     
                   int linhas = stmt.executeUpdate();
                    

                   if(linhas > 0){
                       JOptionPane.showMessageDialog(this, "Veículo desativado com sucesso!");
                   }
               }
       
            
        }else{
                String sqlExcluir = """
                                    DELETE FROM veiculo
                                    WHERE id = ?
                                    """;
                
                try(PreparedStatement stmt = conex.prepareStatement(sqlExcluir)){
                
                    stmt.setInt(1, id);
                    
                    int linhas = stmt.executeUpdate();
                    
                
                if(linhas > 0){
                    JOptionPane.showMessageDialog(this, "Veículo excluído com sucesso!");
                
                }else{
                    JOptionPane.showMessageDialog(this, "Veículo não encontrado!");
                }
              }
           }
        atualizarTabela();
        
    }catch(SQLException erro){
        JOptionPane.showMessageDialog(this, "Erro ao excluir veículo: " + erro.getMessage());
      }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnLocalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLocalizarActionPerformed
        String pesquisa = txtPesquisar.getText().trim();
        
        if(pesquisa.isEmpty()){
            JOptionPane.showMessageDialog(
                    this,
                    "Digite o nome ou parte do nome do Veiculo.",
                    "Pesquisa Vazia",
                     JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        DefaultTableModel modelo = (DefaultTableModel) tblVeiculos.getModel();
        
        modelo.setRowCount(0);
        
        String tipo_pesquisa = cbPesquisarPor.getSelectedItem().toString();
        
        String sql = "";
        
        if(tipo_pesquisa == "ID"){
            sql = """
                  SELECT v.*, c.nome AS cliente
                  FROM veiculo v
                  JOIN cliente c ON v.cliente_id = c.id
                  WHERE v.id = ?
                  ORDER BY v.id
                  """;
        }else if(tipo_pesquisa == "Placa" ){
            sql = """
                   SELECT v.*, c.nome AS cliente
                   FROM veiculo v
                   JOIN cliente c ON v.cliente_id = c.id
                   WHERE v.placa ILIKE ?
                   ORDER BY v.placa
                  """;
        }else if (tipo_pesquisa == "Marca"){
            sql = """
                 SELECT v.*, c.nome AS cliente
                 FROM veiculo v
                 JOIN cliente c ON v.cliente_id = c.id
                 WHERE v.marca ILIKE ?
                 ORDER BY v.marca
                 """;
        }else if(tipo_pesquisa == "Modelo"){
            sql = """
                  SELECT v.*, c.nome AS cliente
                  FROM veiculo v
                  JOIN cliente c ON v.cliente_id = c.id
                  WHERE v.modelo ILIKE ?
                  ORDER BY v.modelo
                  """;
        }else if(tipo_pesquisa == "Cliente"){
            sql = """
                  SELECT v.*, c.nome AS cliente
                  FROM veiculo v
                  JOIN cliente c ON v.cliente_id = c.id
                  WHERE c.nome ILIKE ?
                  ORDER BY c.nome
                  """;
        }else{
            JOptionPane.showMessageDialog(this, "Selecione um tipo de pesquisa válido!");
            return;
        }
        
        try {
            if(tipo_pesquisa == "ID"){
               int id = Integer.parseInt(txtPesquisar.getText().toString());
                
    }
        } catch (NumberFormatException erro) {
        JOptionPane.showMessageDialog(this,
                "Informe valores numéricos válidos!");
        return;

        }
        try (
             Connection conex = Conexao.conectar();
             PreparedStatement stmt = conex.prepareStatement(sql)){
            if(tipo_pesquisa == "ID"){
               int id = Integer.parseInt(txtPesquisar.getText().toString());
                stmt.setInt(1, id);
            }else{
        stmt.setString(1, "%" +pesquisa+ "%");
    }  
            try (ResultSet resultado = stmt.executeQuery()){
                while (resultado.next()){
                    modelo.addRow(new Object [] {
                    resultado.getInt("id"),
                    resultado.getString("cliente"),
                    resultado.getString("placa"),
                    resultado.getString("marca"),
                    resultado.getString("modelo"),
                    resultado.getString("ano"),
                    resultado.getString("cor"),
                    resultado.getString("observacao"),
                    resultado.getBoolean("ativo")});
                }
            }
            if(modelo.getRowCount() ==0) {
                  JOptionPane.showMessageDialog(this,
                            "Nenhum Veículo encontrado para: " + pesquisa,
                            "Resultado da Pesquisa",
                            JOptionPane.INFORMATION_MESSAGE);
            }
        }catch(SQLException erro) {
            JOptionPane.showMessageDialog(this, 
                                          "Erro ao localizar o Veículo:\n" + erro.getMessage(),
                                          "Erro no banco de dados",
                                          JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnLocalizarActionPerformed

    private void btnAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAlterarActionPerformed
        int linha = tblVeiculos.getSelectedRow();
        if(linha == -1){
            JOptionPane.showMessageDialog(this, "Selecione um Veiculo.");
            return;
        }
        
        int posicao = cbCliente.getSelectedIndex();

            if (posicao == -1 || posicao >= idClientes.size()) {
                JOptionPane.showMessageDialog(this,
                    "Selecione um cliente!");
            return;
        }


        
        int id = Integer.parseInt(tblVeiculos.getValueAt(linha, 0).toString());
        int idCliente = idClientes.get(posicao);
        String placa = txtPlaca.getText().trim();
        String marca = txtMarca.getText().trim();
        String modelo = txtModelo.getText().trim();
        String cor = txtCor.getText().trim();
        String obs = txtObs.getText().trim();
        Boolean ativo = chkAtivo.isSelected();
        
        int ano;

            try {
                ano = Integer.parseInt(txtAno.getText().trim());

                     if (ano < 1900 || ano > 2100) {
                              JOptionPane.showMessageDialog(this,
                                "O ano deve estar entre 1900 e 2100!");
                     return;
                 }

                } catch (NumberFormatException erro) {
                         JOptionPane.showMessageDialog(this,
                                   "Informe um ano válido!");
                            return;
            }
        
        int confirmacao = JOptionPane.showConfirmDialog(this,
                                                        "Deseja realmente alterar os dados deste Veiculo?",
                                                        "Confirmar alteração",
                                                        JOptionPane.YES_NO_OPTION);
        
        if(confirmacao != JOptionPane.YES_OPTION) return;
        
        String sql = """
                     UPDATE veiculo
                     SET cliente_id = ?,
                     placa = ?,
                     marca = ?,
                     modelo = ?,
                     ano = ?,
                     cor = ?,
                     observacao = ?,
                     ativo = ?
                     WHERE id = ?
                     """;
        
        try(Connection conex = Conexao.conectar();
            PreparedStatement stmt = conex.prepareStatement(sql)){
                
                stmt.setInt(1, idCliente);
                stmt.setString(2, placa);
                stmt.setString(3, marca);
                stmt.setString(4, modelo);
                stmt.setInt(5, ano);
                stmt.setString(6, cor);
                stmt.setString(7, obs);
                stmt.setBoolean(8, ativo);
                stmt.setInt(9, id);
                
            int linhasAlteradas = stmt.executeUpdate();
            
                if(linhasAlteradas > 0){
                    JOptionPane.showMessageDialog(this,
                                                  "Veiculo alterado com sucesso");
                    atualizarTabela();
                }else{
                    JOptionPane.showMessageDialog(this,
                                                  "veiculo não encontrado");
                }
                
        }catch(SQLException erro){
            JOptionPane.showMessageDialog(this,
                                          "Erro ao alterar veiculo: " +erro.getMessage());
        }
        
    }//GEN-LAST:event_btnAlterarActionPerformed

    private void tblVeiculosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblVeiculosMouseClicked
        int linha = tblVeiculos.getSelectedRow();
        if(linha == -1) return;
        
        txtID.setText(tblVeiculos.getValueAt(linha, 0).toString());
        cbCliente.setSelectedItem(tblVeiculos.getValueAt(linha, 1).toString());
        txtPlaca.setText(tblVeiculos.getValueAt(linha, 2).toString());
        txtMarca.setText(tblVeiculos.getValueAt(linha, 3).toString());
        txtModelo.setText(tblVeiculos.getValueAt(linha, 4).toString());
        txtAno.setText(tblVeiculos.getValueAt(linha, 5).toString());
        txtCor.setText(tblVeiculos.getValueAt(linha, 6).toString());
        txtObs.setText(tblVeiculos.getValueAt(linha, 7).toString());
        chkAtivo.setSelected(Boolean.TRUE.equals(tblVeiculos.getValueAt(linha, 8)));
        
    }//GEN-LAST:event_tblVeiculosMouseClicked

    
